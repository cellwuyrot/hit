import { test, expect } from "@playwright/test";

test("Кампании: черновик, публикация, метатеги, UTM и статистика", async ({ page, request }) => {
  const unauthorized = await request.get("/api/admin/campaigns");
  expect(unauthorized.status()).toBe(401);
  await page.goto("/admin");
  await page.getByPlaceholder("Логин", { exact: true }).fill("e2e-admin");
  await page.getByPlaceholder("Пароль", { exact: true }).fill("e2e-password");
  await page.getByRole("button", { name: "Войти", exact: true }).click();
  await page.getByRole("button", { name: "Сайт и продвижение", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Рекламные кампании" })).toBeVisible();
  await page.getByRole("button", { name: "Создать кампанию" }).click();
  await page.getByLabel("Название для админки *").fill("Проверка рекламы");
  await page.getByLabel("Заголовок страницы H1 *").fill("Наша тестовая подборка");
  await page.getByLabel("Текст подборки").fill("Тестовое описание без HTML");
  await page.getByRole("checkbox", { name: /E2E товар/ }).check();
  await page.getByText("Метатеги и изображение для превью").click();
  await page.getByLabel("Meta title", { exact: true }).fill("Тестовая подборка | ТОПХИТ");
  await page.getByLabel("Meta description", { exact: true }).fill("Описание для поисковика");
  await page.getByRole("button", { name: "Сохранить кампанию" }).click();
  await expect(page.getByText("Кампания сохранена.")).toBeVisible();
  const token = await page.evaluate(() => localStorage.getItem("admin_token"));
  const headers = { Authorization: `Bearer ${token}` };
  let records = await (await request.get("/api/admin/campaigns", { headers })).json();
  let campaign = records.find((x: { name: string }) => x.name === "Проверка рекламы");
  expect(campaign).toBeTruthy();
  expect((await request.get(`/campaign/${campaign.slug}`)).status()).toBe(404);
  await page.getByRole("button", { name: "Изменить", exact: true }).click();
  await page.getByRole("checkbox", { name: /Опубликовать страницу/ }).check();
  await page.getByRole("checkbox", { name: /Разрешить индексацию/ }).check();
  await page.getByRole("button", { name: "Сохранить кампанию" }).click();
  await expect(page.getByText("Кампания сохранена.")).toBeVisible();
  await page.getByRole("button", { name: "Ссылка с UTM" }).click();
  await expect(page.getByLabel("Готовая ссылка")).toHaveValue(new RegExp(`utm_source=yandex.*utm_medium=cpc.*utm_campaign=${campaign.slug}`));
  const view = page.waitForResponse(r => r.url().endsWith("/api/analytics") && r.request().method() === "POST");
  await page.goto(`/campaign/${campaign.slug}?utm_source=yandex&utm_medium=cpc`);
  await expect(page.getByRole("heading", { name: "Наша тестовая подборка" })).toBeVisible();
  await expect(page.getByText("E2E товар").first()).toBeVisible();
  await expect(page).toHaveTitle("Тестовая подборка | ТОПХИТ");
  await expect(page.locator('meta[name="description"]')).toHaveAttribute("content", "Описание для поисковика");
  expect((await view).status()).toBe(200);
  records = await (await request.get("/api/admin/campaigns", { headers })).json();
  campaign = records.find((x: { name: string }) => x.name === "Проверка рекламы");
  expect(campaign.visits30).toBeGreaterThanOrEqual(1);
  expect(campaign.sources).toContainEqual({ source: "yandex", medium: "cpc", visits: 1 });
  const map = await (await request.get("/sitemap.xml")).text();
  expect(map).toContain(`/campaign/${campaign.slug}`);
  const secondView = page.waitForResponse(r => r.url().endsWith("/api/analytics") && r.request().method() === "POST");
  await page.goto(`/campaign/${campaign.slug}?utm_source=vk&utm_medium=cpc`);
  await secondView;
  records = await (await request.get("/api/admin/campaigns", { headers })).json();
  campaign = records.find((x: { name: string }) => x.name === "Проверка рекламы");
  expect(campaign.sources).toContainEqual({ source: "yandex", medium: "cpc", visits: 1 });
  expect(campaign.sources.some((x: { source: string }) => x.source === "vk")).toBe(false);
  const bad = await request.put("/api/admin/campaigns", { headers, data: { ...campaign, productIds: ["missing-product"] } });
  expect(bad.status()).toBe(400);
  const unpublished = await request.put("/api/admin/campaigns", { headers, data: { ...campaign, published: false } });
  expect(unpublished.status()).toBe(200);
  expect((await request.get(`/campaign/${campaign.slug}`)).status()).toBe(404);
  expect((await request.get("/product/e2e-product")).status()).toBe(200);
  expect(await (await request.get("/sitemap.xml")).text()).not.toContain(`/campaign/${campaign.slug}`);
});

test("Категории: создание, подкатегория и безопасное редактирование", async ({ page, request }) => {
  await page.goto("/admin"); await page.getByPlaceholder("Логин", { exact: true }).fill("e2e-admin"); await page.getByPlaceholder("Пароль", { exact: true }).fill("e2e-password"); await page.getByRole("button", { name: "Войти", exact: true }).click();
  await page.getByRole("button", { name: "Каталог", exact: true }).click(); await page.getByRole("button", { name: "Категории", exact: true }).click();
  await page.getByLabel("Название *", { exact: true }).fill("Категория тест 42");
  await page.getByRole("button", { name: "Создать категорию", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Категория сохранена");
  await page.getByLabel("Название *", { exact: true }).fill("Подкатегория тест 42");
  await page.getByLabel("Расположение").selectOption({ label: "Подкатегория: Категория тест 42" });
  await page.getByRole("button", { name: "Создать категорию", exact: true }).click();
  await expect(page.getByText("Подкатегория тест 42", { exact: true })).toBeVisible();
  const row = page.locator("div").filter({ has: page.getByText("Категория тест 42", { exact: true }) }).filter({ has: page.getByRole("button", { name: "Изменить", exact: true }) }).last();
  await row.getByRole("button", { name: "Изменить", exact: true }).click();
  await expect(page.getByLabel("Расположение")).toBeDisabled();
  await page.getByLabel("Название *", { exact: true }).fill("Категория тест 42 обновлена");
  await page.getByRole("button", { name: "Сохранить изменения" }).click();
  await expect(page.getByText("Категория тест 42 обновлена", { exact: true })).toBeVisible();
  const token = await page.evaluate(() => localStorage.getItem("admin_token"));
  const categories = await (await request.get("/api/admin/categories", { headers: { Authorization: `Bearer ${token}` } })).json();
  const parent = categories.find((c: { name: string }) => c.name === "Категория тест 42 обновлена");
  const child = categories.find((c: { name: string }) => c.name === "Подкатегория тест 42");
  expect(child.parentId).toBe(parent.id);
  const deletion = await request.delete("/api/admin/categories", { headers: { Authorization: `Bearer ${token}` }, data: { id: parent.id } });
  expect(deletion.status()).toBe(409);
});

test("Каталог: поиск категорий и безопасная обработка некорректной цены", async ({ page }) => {
  await page.goto("/catalog?priceFrom=abc");
  await expect(page.getByRole("heading", { name: "Каталог товаров" })).toBeVisible();
  await page.getByLabel("Поиск по категориям").fill("E2E");
  await expect(page.getByRole("link", { name: /E2E/ }).first()).toBeVisible();
  await page.getByLabel("Поиск по категориям").fill("нет такой категории");
  await expect(page.getByText("Категории не найдены. Попробуйте другое название.")).toBeVisible();
});

test("Мобильный каталог не перекрывается всплывающей рекомендацией", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/catalog");
  await page.waitForTimeout(8500);
  await expect(page.getByText("Рекомендуем", { exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Фильтры" })).toBeVisible();
});
